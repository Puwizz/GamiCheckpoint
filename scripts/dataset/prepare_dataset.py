from pathlib import Path

# Add project root and src to python path for imports
ROOT = Path(__file__).resolve().parents[2]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from PIL import Image, UnidentifiedImageError

from step_config import ORIGAMI_STEPS, STEP_CLASSES
from utils import safe_rmtree


IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".bmp"}
REQUIRED_SPLITS = ("train", "val", "test")
GENERATED_MARKER = ".gamisenpai_generated_dataset.json"


class DatasetValidationError(ValueError):
    """Raised when raw capture sessions are not safe to use."""

    def __init__(self, errors, warnings=None):
        super().__init__("Raw session audit failed")
        self.errors = list(errors)
        self.warnings = list(warnings or [])


@dataclass(frozen=True)
class ImageRecord:
    split: str
    session: str
    class_name: str
    source_path: Path
    sha256: str
    width: int
    height: int


def parse_args():
    root = ROOT
    parser = argparse.ArgumentParser(
        description="Audit and prepare train/val/test data split by capture session."
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=root / "configs" / "five_session_split.json",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=root / "data" / "step6" / "five_session" / "processed",
    )
    parser.add_argument(
        "--validate-only",
        action="store_true",
        help="Audit the raw sessions without copying files.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Replace an output previously generated by this script.",
    )
    return parser.parse_args()


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as image_file:
        for block in iter(lambda: image_file.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def image_files(directory):
    return sorted(
        path
        for path in directory.iterdir()
        if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES
    )


def find_step_directory(session_dir, step_name):
    """Resolve Step1 and one legacy alias such as Step1_noon."""
    exact = session_dir / step_name
    if exact.is_dir():
        return exact, None

    aliases = sorted(path for path in session_dir.glob(f"{step_name}_*") if path.is_dir())
    if len(aliases) == 1:
        return aliases[0], None
    if len(aliases) > 1:
        names = ", ".join(path.name for path in aliases)
        return None, f"Ambiguous folders for {session_dir.name}/{step_name}: {names}"
    return None, f"Missing folder: {session_dir.name}/{step_name}"


def load_config(config_path, project_root=None):
    config_path = Path(config_path).resolve()
    project_root = Path(project_root or ROOT).resolve()
    try:
        config = json.loads(config_path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise DatasetValidationError([f"Config not found: {config_path}"]) from error
    except json.JSONDecodeError as error:
        raise DatasetValidationError([f"Invalid JSON in {config_path}: {error}"]) from error

    source_value = config.get("source_dir")
    if not isinstance(source_value, str) or not source_value.strip():
        raise DatasetValidationError(["Config source_dir must be a non-empty path string."])
    source_dir = Path(source_value)
    if not source_dir.is_absolute():
        source_dir = project_root / source_dir

    return config, source_dir.resolve(), project_root


def audit_sessions(config, source_dir):
    errors = []
    warnings = []
    records = []
    splits = config.get("splits")
    if not isinstance(splits, dict):
        raise DatasetValidationError(["Config splits must be an object."])

    configured_limits = (
        ("min_images_per_step", config.get("min_images_per_step", 1)),
        ("min_image_width", config.get("min_image_width", 1)),
        ("min_image_height", config.get("min_image_height", 1)),
    )
    limits = {}
    for label, value in configured_limits:
        if not isinstance(value, int) or value < 1:
            errors.append(f"Config {label} must be an integer of at least 1.")
            limits[label] = 1
        else:
            limits[label] = value
    min_images = limits["min_images_per_step"]
    min_width = limits["min_image_width"]
    min_height = limits["min_image_height"]

    split_sessions = {}
    all_session_owners = defaultdict(list)
    for split in REQUIRED_SPLITS:
        sessions = splits.get(split)
        if not isinstance(sessions, list) or not sessions:
            errors.append(f"Config splits.{split} must contain at least one session.")
            sessions = []
        cleaned = []
        for session in sessions:
            if not isinstance(session, str) or not session.strip():
                errors.append(f"Config splits.{split} contains an invalid session name.")
                continue
            if not re.fullmatch(r"[A-Za-z0-9._-]+", session):
                errors.append(
                    f"Session name may use only letters, numbers, dot, underscore, and dash: {session!r}"
                )
                continue
            cleaned.append(session)
            all_session_owners[session].append(split)
        if len(cleaned) != len(set(cleaned)):
            errors.append(f"Config splits.{split} lists the same session more than once.")
        split_sessions[split] = list(dict.fromkeys(cleaned))

    for session, owners in all_session_owners.items():
        if len(set(owners)) > 1:
            errors.append(
                f"Session leakage: {session} appears in multiple splits: {', '.join(owners)}"
            )

    if not source_dir.is_dir():
        errors.append(f"Source directory not found: {source_dir}")
        raise DatasetValidationError(errors, warnings)

    if errors and not all(split_sessions.values()):
        raise DatasetValidationError(errors, warnings)

    for split in REQUIRED_SPLITS:
        for session in split_sessions[split]:
            session_dir = source_dir / session
            if not session_dir.is_dir():
                errors.append(f"Session not found: {session_dir}")
                continue
            for class_name in ORIGAMI_STEPS:
                step_number = class_name.removeprefix("Chk")
                step_dir, step_error = find_step_directory(session_dir, f"Step{step_number}")
                if step_error:
                    errors.append(step_error)
                    continue
                paths = image_files(step_dir)
                if len(paths) < min_images:
                    errors.append(
                        f"{session}/{step_dir.name} has {len(paths)} images; need at least {min_images}."
                    )
                for path in paths:
                    try:
                        with Image.open(path) as image:
                            width, height = image.size
                            image.verify()
                    except (OSError, SyntaxError, UnidentifiedImageError) as error:
                        errors.append(f"Unreadable image {path}: {error}")
                        continue
                    if width < min_width or height < min_height:
                        errors.append(
                            f"Image too small ({width}x{height}, minimum {min_width}x{min_height}): {path}"
                        )
                    records.append(
                        ImageRecord(
                            split=split,
                            session=session,
                            class_name=class_name,
                            source_path=path.resolve(),
                            sha256=sha256(path),
                            width=width,
                            height=height,
                        )
                    )

    by_hash = defaultdict(list)
    for record in records:
        by_hash[record.sha256].append(record)
    for duplicate_records in by_hash.values():
        if len(duplicate_records) < 2:
            continue
        classes = {record.class_name for record in duplicate_records}
        split_names = {record.split for record in duplicate_records}
        examples = ", ".join(
            f"{record.session}/{record.source_path.parent.name}/{record.source_path.name}"
            for record in duplicate_records[:3]
        )
        if len(classes) > 1:
            errors.append(f"Same image has conflicting labels {sorted(classes)}: {examples}")
        if len(split_names) > 1:
            errors.append(
                f"Exact duplicate crosses splits {sorted(split_names)} and would leak data: {examples}"
            )
        elif len(classes) == 1:
            warnings.append(f"Exact duplicate within {next(iter(split_names))}: {examples}")

    if errors:
        raise DatasetValidationError(errors, warnings)
    return records, warnings


def print_audit(records, warnings):
    counts = defaultdict(int)
    for record in records:
        counts[(record.split, record.session, record.class_name)] += 1
    print("Raw session audit PASSED")
    for split in REQUIRED_SPLITS:
        split_records = [record for record in records if record.split == split]
        sessions = sorted({record.session for record in split_records})
        print(f"  {split}: {len(split_records)} images from {len(sessions)} session(s)")
        for session in sessions:
            class_counts = ", ".join(
                f"{class_name}={counts[(split, session, class_name)]}"
                for class_name in STEP_CLASSES
            )
            print(f"    {session}: {class_counts}")
    for warning in warnings:
        print(f"[WARN] {warning}")


def _assert_safe_output(output_dir, source_dir, project_root):
    output_dir = output_dir.resolve()
    protected = {source_dir.resolve(), project_root.resolve(), project_root.resolve().parent}
    if output_dir in protected:
        raise ValueError(f"Refusing unsafe output directory: {output_dir}")
    if output_dir in source_dir.resolve().parents:
        raise ValueError(f"Output directory cannot contain the raw source directory: {output_dir}")
    if source_dir.resolve() in output_dir.parents:
        raise ValueError(f"Output directory cannot be inside the raw source directory: {output_dir}")


def prepare_output(records, output_dir, source_dir, project_root, config_path, overwrite=False):
    output_dir = Path(output_dir).resolve()
    _assert_safe_output(output_dir, source_dir, project_root)
    marker_path = output_dir / GENERATED_MARKER
    if output_dir.exists() and any(output_dir.iterdir()):
        if not overwrite:
            raise FileExistsError(
                f"Output already exists: {output_dir}. Use --overwrite only to rebuild generated data."
            )
        existing_names = set(p.name for p in output_dir.iterdir())
        is_known_generated = (
            marker_path.is_file()
            or (output_dir / "session_manifest.csv").is_file()
            or (output_dir / "dataset_summary.json").is_file()
            or existing_names.issubset({"train", "val", "test", "session_manifest.csv", "dataset_summary.json", GENERATED_MARKER})
        )
        if not is_known_generated:
            raise ValueError(
                f"Refusing to overwrite an unmarked directory: {output_dir}. "
                f"Expected marker {GENERATED_MARKER}."
            )
        safe_rmtree(output_dir)

    output_dir.mkdir(parents=True, exist_ok=True)
    marker_path.write_text(
        json.dumps(
            {
                "generator": "scripts/prepare_dataset.py",
                "schema_version": 1,
                "config": str(Path(config_path).resolve()),
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    rows = []
    counters = defaultdict(int)
    for record in records:
        key = (record.split, record.session, record.class_name)
        counters[key] += 1
        destination_dir = output_dir / record.split / record.class_name
        destination_dir.mkdir(parents=True, exist_ok=True)
        destination_name = (
            f"{record.session}__{counters[key]:03d}__{record.source_path.name}"
        )
        destination = destination_dir / destination_name
        shutil.copy2(record.source_path, destination)
        row = asdict(record)
        row["source_path"] = str(record.source_path)
        row["output_path"] = str(destination.relative_to(output_dir))
        rows.append(row)

    manifest_path = output_dir / "session_manifest.csv"
    fieldnames = [
        "split",
        "session",
        "class_name",
        "source_path",
        "output_path",
        "sha256",
        "width",
        "height",
    ]
    with manifest_path.open("w", newline="", encoding="utf-8") as manifest_file:
        writer = csv.DictWriter(manifest_file, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    counts = {
        split: {
            class_name: sum(
                record.split == split and record.class_name == class_name for record in records
            )
            for class_name in STEP_CLASSES
        }
        for split in REQUIRED_SPLITS
    }
    summary_path = output_dir / "dataset_summary.json"
    summary_path.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "source_dir": str(source_dir),
                "config": str(Path(config_path).resolve()),
                "classes": list(STEP_CLASSES),
                "counts": counts,
                "total_images": len(records),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return manifest_path, summary_path


def print_failure(error):
    print("Raw session audit FAILED", file=sys.stderr)
    for message in error.errors:
        print(f"[ERROR] {message}", file=sys.stderr)
    for message in error.warnings:
        print(f"[WARN] {message}", file=sys.stderr)


def main():
    args = parse_args()
    try:
        config, source_dir, project_root = load_config(args.config)
        records, warnings = audit_sessions(config, source_dir)
        print_audit(records, warnings)
        if args.validate_only:
            return 0
        manifest_path, summary_path = prepare_output(
            records,
            args.output_dir,
            source_dir,
            project_root,
            args.config,
            overwrite=args.overwrite,
        )
    except DatasetValidationError as error:
        print_failure(error)
        return 1
    except (FileExistsError, ValueError, OSError) as error:
        print(f"Dataset preparation FAILED: {error}", file=sys.stderr)
        return 1

    print("Prepared five-session dataset")
    print(f"  output={args.output_dir.resolve()}")
    print(f"  manifest={manifest_path}")
    print(f"  summary={summary_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
